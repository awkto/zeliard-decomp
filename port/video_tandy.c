/* video_tandy.c — GMTGA.BIN (docs/VIDEO_DRIVERS.md §2.5).
 *
 * INT 10h mode 9, 320x200x16 in B800 (two pixels a byte, four 8 KB banks).
 * `[0x2044]` @2DF6 turns each PC-88 pair `(l<<3|r)` into a 4-bit colour through
 * the 64-entry table @2999 — an approximation of the MCGA additive blend with
 * the fixed 16 CGA colours — so like CGA the whole screen is one lookup from
 * the pair buffer.  The mode-9 default palette is used unchanged: the driver
 * writes no ports at all. */
#include "video.h"
#include "render.h"

/* GMTGA.BIN @2999, rows l = blk wht red grn cyn blu yel mag; values are
 * CGA/Tandy 16-colour indices.  Note blk+blk = 0 while the driver's plain
 * "black" text colour (@262E) is 8 — bright-set black. */
const uint8_t VID_TGA_PAIR[64] = {
    0x0, 0x7, 0x4, 0x2, 0x3, 0x1, 0x8, 0x5,     /* blk */
    0x7, 0xF, 0xC, 0xE, 0xB, 0x9, 0xE, 0xD,     /* wht */
    0x4, 0xC, 0xC, 0xE, 0x7, 0x5, 0x6, 0xC,     /* red */
    0x2, 0xE, 0xE, 0xA, 0xA, 0x3, 0xA, 0x7,     /* grn */
    0x3, 0xB, 0x7, 0xA, 0xB, 0x9, 0xA, 0x9,     /* cyn */
    0x1, 0x9, 0x5, 0x3, 0x9, 0x9, 0x7, 0x5,     /* blu */
    0x8, 0xE, 0x6, 0xA, 0xA, 0x7, 0xE, 0xC,     /* yel */
    0x5, 0xD, 0xC, 0x7, 0x9, 0x5, 0xC, 0xD,     /* mag */
};

/* the stock 16-colour CGA/Tandy/EGA palette mode 9 comes up with */
static const uint8_t TGA_RGB[16][3] = {
    { 0x00, 0x00, 0x00 }, { 0x00, 0x00, 0xAA }, { 0x00, 0xAA, 0x00 }, { 0x00, 0xAA, 0xAA },
    { 0xAA, 0x00, 0x00 }, { 0xAA, 0x00, 0xAA }, { 0xAA, 0x55, 0x00 }, { 0xAA, 0xAA, 0xAA },
    { 0x55, 0x55, 0x55 }, { 0x55, 0x55, 0xFF }, { 0x55, 0xFF, 0x55 }, { 0x55, 0xFF, 0xFF },
    { 0xFF, 0x55, 0x55 }, { 0xFF, 0x55, 0xFF }, { 0xFF, 0xFF, 0x55 }, { 0xFF, 0xFF, 0xFF },
};

void video_tandy_to_rgb(const uint8_t *fb, uint8_t *rgb)
{
    for (int i = 0; i < FB_W * FB_H; i++) {
        const uint8_t *p = TGA_RGB[VID_TGA_PAIR[fb[i] & 63]];
        rgb[i * 3] = p[0]; rgb[i * 3 + 1] = p[1]; rgb[i * 3 + 2] = p[2];
    }
}
